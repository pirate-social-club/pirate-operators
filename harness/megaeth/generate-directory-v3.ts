// Generate only from the actual pinned local compiler artifact. No provider calls.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { keccak256, type Hex } from "viem";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

export function generateDirectoryV3() {
  const artifact = JSON.parse(
    readFileSync(
      "out/CommunityDirectoryV3.sol/CommunityDirectoryV3.json",
      "utf8",
    ),
  );
  const metadata =
    typeof artifact.metadata === "string"
      ? JSON.parse(artifact.metadata)
      : artifact.metadata;
  if (
    metadata.compiler.version !== "0.8.30+commit.73712a01" ||
    metadata.settings.evmVersion !== "cancun" ||
    metadata.settings.optimizer.enabled !== true ||
    metadata.settings.optimizer.runs !== 200 ||
    (metadata.settings.viaIR !== undefined &&
      metadata.settings.viaIR !== false) ||
    metadata.settings.compilationTarget[
      "contracts/community/CommunityDirectoryV3.sol"
    ] !== "CommunityDirectoryV3"
  ) {
    throw new Error("wrong_directory_build_profile");
  }
  const runtime: unknown = artifact.deployedBytecode.object;
  if (
    typeof runtime !== "string" ||
    !/^0x(?:[0-9a-f]{2})+(?![\s\S])/.test(runtime) ||
    (runtime.length - 2) / 2 > 24576 ||
    Object.keys(artifact.deployedBytecode.immutableReferences ?? {}).length
  ) {
    throw new Error("invalid_directory_runtime");
  }
  const abi = artifact.abi;
  if (
    !Array.isArray(abi) ||
    !abi.some(
      (entry) =>
        entry.type === "function" && entry.name === "registerHostedCommunity",
    )
  ) {
    throw new Error("wrong_directory_abi");
  }
  const profile = {
    schema: "pirate.directory-build/3",
    compiler: metadata.compiler.version,
    evmVersion: "cancun",
    optimizerRuns: 200,
    viaIR: false,
    abiSha256: `0x${createHash("sha256").update(JSON.stringify(abi)).digest("hex")}`,
    runtimeCodeHash: keccak256(runtime as Hex),
    runtimeBytes: (runtime.length - 2) / 2,
    sources: metadata.sources,
  };
  writeFileSync(
    "packages/community/generated/directory-v3.ts",
    "// Generated by harness/megaeth/generate-directory-v3.ts from actual solc output.\n" +
      "export const directoryV3Abi = " +
      JSON.stringify(abi, null, 2) +
      " as const;\n" +
      "export const directoryV3Build = " +
      JSON.stringify(profile, null, 2) +
      " as const;\n" +
      "export const directoryV3Runtime = " +
      JSON.stringify(runtime) +
      " as const;\n",
  );
  console.log(
    JSON.stringify({
      runtimeBytes: profile.runtimeBytes,
      runtimeCodeHash: profile.runtimeCodeHash,
      abiSha256: profile.abiSha256,
    }),
  );
}
if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
)
  generateDirectoryV3();
